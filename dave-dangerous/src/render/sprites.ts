export interface SpriteRect { x: number; y: number; w: number; h: number; }
export const SPRITE_RECTS: Map<string, SpriteRect> = new Map();

/** Packs named 16×16 sprites into an atlas canvas and records rects. DOM-only. */
export function buildSpriteAtlas(color?: (i: number) => number): HTMLCanvasElement {
  const names = Object.keys(SPRITES);
  const cols = Math.ceil(Math.sqrt(names.length));
  const canvas = document.createElement("canvas");
  canvas.width = cols * 16;
  canvas.height = Math.ceil(names.length / cols) * 16;
  const ctx = canvas.getContext("2d")!;
  const palette = color ?? ((i: number) => PALETTE_0[i]!);
  names.forEach((name, idx) => {
    const tx = (idx % cols) * 16;
    const ty = Math.floor(idx / cols) * 16;
    const rows = SPRITES[name]!;
    for (let y = 0; y < 16; y++) {
      for (let x = 0; x < 16; x++) {
        const p = Number(rows[y]![x]!);
        if (p === 0) continue;
        ctx.fillStyle = `#${palette(p).toString(16).padStart(6, "0")}`;
        ctx.fillRect(tx + x, ty + y, 1, 1);
      }
    }
    SPRITE_RECTS.set(name, { x: tx, y: ty, w: 16, h: 16 });
  });
  return canvas;
}

const ATLAS_COLS = Math.ceil(Math.sqrt(Object.keys(SPRITES).length));

/** DOM-free sprite sheet: the host supplies a canvas 2D context; each sprite is painted
 *  into that atlas lazily at the same (col*16, rowIdx*16) slot buildSpriteAtlas uses,
 *  then draw() blits it with scale/flip. Safe to construct in non-DOM test environments. */
export class SpriteSheet {
  readonly canvas: HTMLCanvasElement;
  private readonly ctx: CanvasRenderingContext2D;
  private readonly palette: number[];
  private readonly painted = new Set<string>();

  constructor(ctx: CanvasRenderingContext2D, palette: number[] = PALETTE_0) {
    this.ctx = ctx;
    this.canvas = ctx.canvas;
    this.palette = palette;
    this.canvas.width = ATLAS_COLS * 16;
    this.canvas.height = Math.ceil(Object.keys(SPRITES).length / ATLAS_COLS) * 16;
  }

  /** Blits the named sprite at (x, y); paints it into the atlas on first use. */
  draw(ctx: CanvasRenderingContext2D, name: string, x: number, y: number, scale = 1, flipX = false): void {
    const rows = SPRITES[name];
    if (!rows) return;
    if (!this.painted.has(name)) {
      const idx = Object.keys(SPRITES).indexOf(name);
      const tx = (idx % ATLAS_COLS) * 16;
      const ty = Math.floor(idx / ATLAS_COLS) * 16;
      for (let py = 0; py < 16; py++) {
        for (let px = 0; px < 16; px++) {
          const p = Number(rows[py]![px]!);
          if (p === 0) continue;
          this.ctx.fillStyle = `#${this.palette[p]!.toString(16).padStart(6, "0")}`;
          this.ctx.fillRect(tx + px, ty + py, 1, 1);
        }
      }
      SPRITE_RECTS.set(name, { x: tx, y: ty, w: 16, h: 16 });
      this.painted.add(name);
    }
    const r = SPRITE_RECTS.get(name)!;
    ctx.save();
    ctx.imageSmoothingEnabled = false;
    ctx.translate(x + (flipX ? 16 * scale : 0), y);
    ctx.scale(flipX ? -scale : scale, scale);
    ctx.drawImage(this.canvas, r.x, r.y, r.w, r.h, 0, 0, r.w, r.h);
    ctx.restore();
  }
}
