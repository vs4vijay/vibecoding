// - g() also pads the row COUNT to 16 with transparent "0" rows: 8 brief grids list
//   fewer than 16 rows while the brief's own test requires exactly 16.
// - tile_tree used palette index '4'; remapped to '1' (indices must stay within 0-3).
// - SpriteSheet added per the brief's DOM-free drawing approach (ctx in constructor);
//   SPRITE_RECTS / buildSpriteAtlas are verbatim.
export const PALETTE_0 = [0x000000, 0x00aa00, 0xaa00aa, 0xaaaaaa];
export const PALETTE_1 = [0x000000, 0xaa0000, 0x00aaaa, 0xffffff];

const g = (body: string[]) => {
  const rows = body.map(r => r.padEnd(16, "0").slice(0, 16));
  while (rows.length < 16) rows.push("0000000000000000");
  return rows;
};

